package com.example.myplayer

import android.util.Log
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import org.schabi.newpipe.extractor.NewPipe
import org.schabi.newpipe.extractor.ServiceList
import org.schabi.newpipe.extractor.stream.StreamInfo

data class SubtitleTrack(
    val languageCode: String,
    val displayName: String,
    val url: String,
    val isAutoGenerated: Boolean
)

object YouTubeStream {

    private const val TAG = "YouTubeStream"

    data class StreamResult(
        val videoUrl: String?,
        val audioUrl: String?,
        val muxedUrl: String?,
        val title: String,
        val debug: String,
        val subtitles: List<SubtitleTrack> = emptyList()
    ) {
        val hasAny: Boolean
            get() = muxedUrl != null || videoUrl != null || audioUrl != null
    }

    suspend fun extract(videoId: String): StreamResult = withContext(Dispatchers.IO) {
        val sb = StringBuilder()
        try {
            try { NewPipe.init(DownloaderImpl()) } catch (e: Exception) { }

            val url = "https://www.youtube.com/watch?v=$videoId"
            sb.append("URL: $url\n")

            val info = try {
                StreamInfo.getInfo(ServiceList.YouTube, url)
            } catch (e: Exception) {
                sb.append("getInfo FAIL: ${e.javaClass.simpleName}: ${e.message}\n")
                return@withContext StreamResult(null, null, null, "", sb.toString())
            }

            val title = info.name ?: ""
            sb.append("title: $title\n")
            sb.append("videoStreams: ${info.videoStreams.size}\n")
            sb.append("audioStreams: ${info.audioStreams.size}\n")

            // 자막 트랙 수집
            val subtitleList = mutableListOf<SubtitleTrack>()
            try {
                val subs = info.subtitles
                if (subs != null) {
                    for (s in subs) {
                        val lang = try { s.languageTag } catch (e: Exception) { null } ?: ""
                        if (lang.isBlank()) continue
                        val display = try { s.displayLanguageName } catch (e: Exception) { null } ?: lang
                        val u = try { s.content } catch (e: Exception) { null } ?: continue
                        val auto = try { s.isAutoGenerated } catch (e: Exception) { false }
                        subtitleList.add(
                            SubtitleTrack(
                                languageCode = lang,
                                displayName = display,
                                url = u,
                                isAutoGenerated = auto
                            )
                        )
                    }
                }
                sb.append("subtitles: ${subtitleList.size}\n")
            } catch (e: Exception) {
                sb.append("subtitle err: ${e.message}\n")
            }

            val muxed = info.videoStreams.firstOrNull { !it.isVideoOnly && it.isUrl }
            if (muxed != null) {
                sb.append("muxed: ${muxed.resolution}\n")
                return@withContext StreamResult(null, null, muxed.content, title, sb.toString(), subtitleList)
            }

            val video = try {
                info.videoStreams.filter { it.isVideoOnly && it.isUrl }.maxByOrNull { it.resolution }
            } catch (e: Exception) { null }
            val audio = try {
                info.audioStreams.filter { it.isUrl }.maxByOrNull { it.averageBitrate }
            } catch (e: Exception) { null }

            sb.append("video: ${video?.resolution}\n")
            sb.append("audio: ${audio?.averageBitrate}\n")

            when {
                video != null && audio != null ->
                    StreamResult(video.content, audio.content, null, title, sb.toString(), subtitleList)
                video != null ->
                    StreamResult(video.content, null, null, title, sb.toString(), subtitleList)
                audio != null ->
                    StreamResult(null, audio.content, null, title, sb.toString(), subtitleList)
                else -> StreamResult(null, null, null, title, sb.toString(), subtitleList)
            }
        } catch (e: Exception) {
            sb.append("OUTER: ${e.javaClass.simpleName}: ${e.message}\n")
            StreamResult(null, null, null, "", sb.toString())
        }
    }
}
