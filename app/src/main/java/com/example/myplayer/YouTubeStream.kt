    // ★★★ WARP+POT 서버 API (IP 봇 판정 우회)
    private const val SERVER_API_URL = "http://155.248.161.40:5000"

    private fun flogServer(msg: String) {
        android.util.Log.d(TAG, "[SRV] $msg")
        try {
            val f = java.io.File(MyApp.instance.filesDir, "audio_diag.log")
            val ts = java.text.SimpleDateFormat("HH:mm:ss.SSS", java.util.Locale.US).format(java.util.Date())
            f.appendText("[$ts] [SRV] $msg\n")
        } catch (_: Exception) {}
    }

    private suspend fun fetchFromServer(videoId: String): String? = withContext(Dispatchers.IO) {
        try {
            flogServer("request: $videoId")
            val token = getJwtToken() ?: run {
                flogServer("no jwt token")
                return@withContext null
            }
            val conn = java.net.URL("$SERVER_API_URL/stream?v=$videoId").openConnection() as java.net.HttpURLConnection
            conn.connectTimeout = 5000
            conn.readTimeout = 45000
            conn.requestMethod = "GET"
            conn.setRequestProperty("Authorization", "Bearer $token")
            if (conn.responseCode !in 200..299) {
                flogServer("HTTP ${conn.responseCode}")
                return@withContext null
            }
            val body = conn.inputStream.bufferedReader().use { it.readText() }
            val json = org.json.JSONObject(body)
            val url = json.optString("url", "")
            if (url.isBlank()) {
                flogServer("no url: ${body.take(200)}")
                return@withContext null
            }
            flogServer("OK url=${url.take(60)}")
            url
        } catch (e: Exception) {
            flogServer("err: ${e.message}")
            null
        }
    }

    private fun getJwtToken(): String? {
        return try {
            MyApp.instance.getSharedPreferences("server_auth", android.content.Context.MODE_PRIVATE)
                .getString("jwt", null)?.takeIf { it.isNotBlank() }
        } catch (_: Exception) { null }
    }

    private fun flog(msg: String) {
        android.util.Log.d(TAG, msg)
        try {
            val f = java.io.File(MyApp.instance.filesDir, "audio_diag.log")
            if (f.exists() && f.length() > 500_000) f.writeText("")
            val ts = java.text.SimpleDateFormat("HH:mm:ss.SSS", java.util.Locale.US).format(java.util.Date())
            f.appendText("[$ts] [YTS] $msg\n")
        } catch (_: Exception) {}
    }

    // ─────────────────────────────────────────
    // 캐시 (5분 TTL)
    // ─────────────────────────────────────────
    private data class CachedStream(
        val result: StreamResult,
        val timestamp: Long
    )
    private val streamCache = mutableMapOf<String, CachedStream>()
    private const val CACHE_TTL_MS = 30 * 60 * 1000L

    private fun getCached(videoId: String): StreamResult? {
        val cached = streamCache[videoId] ?: return null
        if (System.currentTimeMillis() - cached.timestamp > CACHE_TTL_MS) {
            streamCache.remove(videoId)
            return null
        }
        return cached.result
    }

    private fun putCache(videoId: String, result: StreamResult) {
        streamCache[videoId] = CachedStream(result, System.currentTimeMillis())
        if (streamCache.size > 100) {
            val oldest = streamCache.minByOrNull { it.value.timestamp }
            oldest?.let { streamCache.remove(it.key) }
        }
    }

    data class StreamResult(
        val videoUrl: String?,
        val audioUrl: String?,
        val muxedUrl: String?,
        val title: String,
        val channelName: String,
        val description: String,
        val debug: String,
        val subtitles: List<SubtitleTrack> = emptyList(),
        val qualities: List<VideoQuality> = emptyList(),
        val audioUrlBest: String? = null,
        val isLive: Boolean = false
    ) {
        val hasAny: Boolean
            get() = muxedUrl != null || videoUrl != null || audioUrl != null
    }

    /** ★ 오디오 모드 전용: muxed 대신 audio-only 스트림 우선 */
    suspend fun extractAudioOnly(videoId: String): StreamResult = withContext(Dispatchers.IO) {
        flog("A1 extractAudioOnly IO 진입: $videoId")

        // ★★★ 1순위: 서버 API (WARP+POT)
        val serverUrl = fetchFromServer(videoId)
        if (!serverUrl.isNullOrBlank()) {
            val r = StreamResult(
                videoUrl = null,
                audioUrl = serverUrl,
                muxedUrl = null,
                title = "",
                channelName = "",
                description = "",
                debug = "server-api OK",
                audioUrlBest = serverUrl
            )
            putCache(videoId, r)
            return@withContext r
        }
        flogServer("fallback to local extract")

        getCached(videoId)?.let {
            Log.d(TAG, "audio-only cache hit: $videoId")
            return@withContext it
        }
        flog("A2 extractAudioOnly → extract 호출: $videoId")

        val full = extract(videoId)
        flog("A3 extractAudioOnly ← extract 복귀: hasAny=${full.hasAny}")
        val audioUrl = full.audioUrlBest ?: full.audioUrl
        if (audioUrl != null) {
            val audioOnly = full.copy(
                muxedUrl = null,
                videoUrl = null,
                audioUrl = audioUrl,
                audioUrlBest = audioUrl
            )
            putCache(videoId, audioOnly)
            return@withContext audioOnly
        }
        full
    }

    /**
     * ★ 최적화된 스트림 추출
     * 1) Piped 우선 (1~2초, 360p muxed)
     * 2) Invidious (실패 예상, 1.5초 타임아웃)
     * 3) NewPipe 폴백 (5~18초, 고화질 muxed)
     *
     * Piped의 itag=18 muxed를 최우선으로 쓰고, 실패하면 NewPipe로.
     */
    suspend fun extract(videoId: String): StreamResult = withContext(Dispatchers.IO) {
        flog("B1 extract IO 진입: $videoId")
        getCached(videoId)?.let {
            Log.d(TAG, "cache hit: $videoId")
            return@withContext it
        }

        val sb = StringBuilder()
        sb.append("extract with InnerTube priority\n")

        // ★★★ 1순위: InnerTube (ydpy 방식) - 직접 googlevideo URL
        try {
            flog("B2 InnerTube 호출 직전: $videoId")
            val innerTube = InnerTubeExtractor.extract(videoId)
            flog("B3 InnerTube 복귀: hasAny=${innerTube.hasAny}")
            flog("B3-debug: ${innerTube.debug.take(1200)}")
            if (!innerTube.hasAny &&
                (innerTube.debug.contains("HARD_FAIL:") ||
                 innerTube.debug.contains("LOGIN_REQUIRED") ||
                 innerTube.debug.contains("UNPLAYABLE"))) {
                flog("⚡ hard-fail 감지 → 폴백 스킵")
                val r = StreamResult(
                    videoUrl = null, audioUrl = null, muxedUrl = null,
                    title = "", channelName = "", description = "",
                    debug = innerTube.debug
                )
                putCache(videoId, r)
                return@withContext r
            }
            if (innerTube.hasAny) {
                sb.append("→ InnerTube OK (itag=${innerTube.audioItag})\n")
                Log.d(TAG, "InnerTube 성공: audio=${innerTube.audioUrl?.take(50)}")
                val result = StreamResult(
                    videoUrl = null,
                    audioUrl = innerTube.audioUrl,
                    muxedUrl = innerTube.muxedUrl,
                    title = innerTube.title,
                    channelName = innerTube.channel,
                    description = "",
                    debug = sb.toString(),
                    audioUrlBest = innerTube.audioUrl
                )
                putCache(videoId, result)
                return@withContext result
            }
            sb.append("InnerTube 실패 → fallback\n")
        } catch (e: Exception) {
            sb.append("InnerTube err: ${e.message?.take(60)}\n")
        }

        // ★ 2순위: NewPipe (기존)
        val result = coroutineScope {
            val pipedDeferred = async<StreamResult?>(Dispatchers.IO) {
                // ★ Piped 완전 skip (8개 서버 timeout 방지)
                null
            }
            // ★ Invidious 현재 완전 다운 → skip (타입 명시)
            val invDeferred: kotlinx.coroutines.Deferred<StreamResult?> =
                kotlinx.coroutines.CompletableDeferred(null)
            // ★ 진단용: NewPipe 폴백 임시 비활성화
            val npDeferred: kotlinx.coroutines.Deferred<StreamResult?> =
                kotlinx.coroutines.CompletableDeferred(null)

            // ★ Piped 우선 (빠름)
            val piped = pipedDeferred.await()
            if (piped != null && piped.hasAny) {
                sb.append("→ piped fast path\n")
                return@coroutineScope piped
            }

            // ★ Invidious 폴백 (지금 실패 상태, 빠른 실패)
            val inv = invDeferred.await()
            if (inv != null && inv.hasAny) {
                sb.append("→ inv fallback\n")
                return@coroutineScope inv
            }

            // ★ NewPipe 최후 폴백 (18초)
            val np = npDeferred.await()
            if (np != null && np.hasAny) {
                sb.append("→ np fallback (slow)\n")
                return@coroutineScope np
            }

            null
        }

        if (result != null && result.hasAny) {
            putCache(videoId, result)
            return@withContext result
        }

        sb.append("모든 소스 실패\n")
        StreamResult(null, null, null, "", "", "", sb.toString())
    }

    // ─────────────────────────────────────────
    // Piped: muxed(itag=18) 우선 반환
    // ─────────────────────────────────────────
    private suspend fun tryPiped(videoId: String, sb: StringBuilder): StreamResult? {
        val prefs = MyApp.instance.getSharedPreferences(
            "server_priority", android.content.Context.MODE_PRIVATE
        )

        val aliveServers = try {
            ServerHealthChecker.getAlivePiped(MyApp.instance)
        } catch (_: Exception) {
            YouTubeApiHelper.PIPED
        }
        if (aliveServers.isEmpty()) return null

        // ★ 로테이션은 살아있는 상위 2개 서버만 (죽은 서버 시도 X)
        val liveServers = aliveServers.take(2)
        val hashIdx = kotlin.math.abs(videoId.hashCode()) % liveServers.size
        val servers = liveServers.drop(hashIdx) + liveServers.take(hashIdx)
        sb.append("piped rotation: idx=$hashIdx, first=${servers.firstOrNull()?.take(40)}, total=${servers.size}\n")

        // ★ Piped 실패 곡 캐시 (다음엔 시도 skip)
        val pipedFailed = MyApp.instance.getSharedPreferences("piped_fail", android.content.Context.MODE_PRIVATE)
            .getStringSet("failed", emptySet()) ?: emptySet()
        if (videoId in pipedFailed) {
            sb.append("piped skip (previously failed): $videoId\n")
            return null
        }

        for (inst in servers) {
            try {
                val conn = java.net.URL("$inst/streams/$videoId").openConnection() as java.net.HttpURLConnection
                conn.connectTimeout = 2000
                conn.readTimeout = 5000
                conn.setRequestProperty("User-Agent", "Mozilla/5.0")
                if (conn.responseCode !in 200..299) {
                    // ★ 500 등 실패 → 캐시 저장
                    if (conn.responseCode in 400..599) {
                        try {
                            val failPref = MyApp.instance.getSharedPreferences("piped_fail", android.content.Context.MODE_PRIVATE)
                            val existing = failPref.getStringSet("failed", mutableSetOf())?.toMutableSet() ?: mutableSetOf()
                            existing.add(videoId)
                            // 최대 100개 유지
                            if (existing.size > 100) {
                                val sorted = existing.take(100).toSet()
                                failPref.edit().putStringSet("failed", sorted).apply()
                            } else {
                                failPref.edit().putStringSet("failed", existing).apply()
                            }
                            sb.append("piped fail cached: $videoId (code=${conn.responseCode})\n")
                        } catch (_: Exception) {}
                    }
                    continue
                }
                val json = org.json.JSONObject(conn.inputStream.bufferedReader().use { it.readText() })

                val title = json.optString("title", "")
                val author = json.optString("uploader", "")

                var audioUrl: String? = null
                var audioBitrate = 0
                var videoUrl: String? = null
                var videoHeight = 0
                var muxed: String? = null
                var bestMuxedH = 0
                val qualities = mutableListOf<VideoQuality>()

                // 오디오 스트림 (현재 Piped는 0개인 경우 많음)
                json.optJSONArray("audioStreams")?.let { aStreams ->
                    for (i in 0 until aStreams.length()) {
                        val f = aStreams.getJSONObject(i)
                        val br = f.optInt("bitrate", 0)
                        val u = f.optString("url", "")
                        if (u.isNotBlank() && br > audioBitrate) {
                            audioBitrate = br
                            audioUrl = u
                        }
                    }
                }

                // 비디오 스트림
                json.optJSONArray("videoStreams")?.let { vStreams ->
                    for (i in 0 until vStreams.length()) {
                        val f = vStreams.getJSONObject(i)
                        val q = f.optString("quality", "")
                        val u = f.optString("url", "")
                        val itag = f.optString("itag", "").toIntOrNull() ?: 0
                        val onlyVideo = f.optBoolean("videoOnly", false)
                        val mime = f.optString("mimeType", "")
                        
                        // ★ height: 숫자 우선, 없으면 quality("360p")에서 파싱, itag 폴백
                        var h = f.optInt("height", 0)
                        if (h <= 0) {
                            // quality 문자열 "360p" → 360
                            h = q.replace("p", "").filter { it.isDigit() }.toIntOrNull() ?: 0
                        }
                        if (h <= 0) {
                            h = YouTubeApiHelper.itagToHeight(itag)
                        }
                        
                        if (u.isBlank()) continue

                        // ★ LBRY (Odysee 미러) 제외
                        if (q.contains("LBRY", ignoreCase = true) ||
                            u.contains("odycdn.com")) continue
                        // ★ HLS 제외
                        if (mime.contains("mpegurl", ignoreCase = true)) continue

                        // ★ itag=18 = muxed 확정 (height 무관)
                        if (itag == 18 || !onlyVideo) {
                            if (h >= bestMuxedH) {
                                bestMuxedH = h
                                muxed = u
                            }
                        }
                        // video-only
                        if (h > videoHeight) {
                            videoHeight = h
                            videoUrl = u
                        }
                        // 화질 옵션
                        if (h > 0) {
                            qualities.add(VideoQuality("${h}p", h, u, onlyVideo))
                        }
                    }
                }

                // ★ muxed 우선 반환 (가장 빠른 재생)
                if (muxed != null) {
                    try {
                        prefs.edit().putString("piped_top", inst).apply()
                    } catch (_: Exception) {}
                    sb.append("piped OK muxed($inst): h=${bestMuxedH}p\n")
                    return StreamResult(
                        videoUrl = null,
                        audioUrl = null,
                        muxedUrl = muxed,
                        title = title,
                        channelName = author,
                        description = "",
                        debug = sb.toString(),
                        qualities = qualities.distinctBy { it.label }.sortedByDescending { it.height },
                        audioUrlBest = null
                    )
                }

                // muxed 없으면 video+audio
                if (audioUrl != null && videoUrl != null) {
                    try {
                        prefs.edit().putString("piped_top", inst).apply()
                    } catch (_: Exception) {}
                    sb.append("piped OK va($inst): a=$audioUrl v=$videoUrl\n")
                    return StreamResult(
                        videoUrl = videoUrl,
                        audioUrl = audioUrl,
                        muxedUrl = null,
                        title = title,
                        channelName = author,
                        description = "",
                        debug = sb.toString(),
                        qualities = qualities.distinctBy { it.label }.sortedByDescending { it.height },
                        audioUrlBest = audioUrl
                    )
                }
            } catch (_: Exception) {}
        }
        return null
    }

    // ─────────────────────────────────────────
    // Invidious (현재 실패, 폴백용)
    // ─────────────────────────────────────────
    private suspend fun tryInvidious(videoId: String, sb: StringBuilder): StreamResult? {
        val aliveServers = try {
            ServerHealthChecker.getAliveInvidious(MyApp.instance)
        } catch (_: Exception) {
            YouTubeApiHelper.INVIDIOUS
        }

        val prefs = MyApp.instance.getSharedPreferences(
            "server_priority", android.content.Context.MODE_PRIVATE
        )
        val topServer = prefs.getString("invidious_top", null)
        val servers = mutableListOf<String>()
        if (topServer != null && topServer in aliveServers) servers.add(topServer)
        servers.addAll(aliveServers.filter { it != topServer })

        for (inst in servers) {
            try {
                val conn = java.net.URL("$inst/api/v1/videos/$videoId").openConnection() as java.net.HttpURLConnection
                conn.connectTimeout = 2000
                conn.readTimeout = 4000
                conn.setRequestProperty("User-Agent", "Mozilla/5.0")
                if (conn.responseCode !in 200..299) continue
                val body = conn.inputStream.bufferedReader().use { it.readText() }
                // ★ 빈 응답 방어
                if (body.length < 100) continue
                val json = org.json.JSONObject(body)
                if (json.optBoolean("liveNow", false)) continue

                val title = json.optString("title", "")
                val author = json.optString("author", "")
                var audioUrl: String? = null
                var audioBitrate = 0
                var videoUrl: String? = null
                var videoHeight = 0
                var muxed: String? = null
                var bestMuxedH = 0

                json.optJSONArray("adaptiveFormats")?.let { formats ->
                    for (i in 0 until formats.length()) {
                        val f = formats.getJSONObject(i)
                        val type = f.optString("type", f.optString("encoding", "")).lowercase()
                        val u = f.optString("url", "")
                        if (u.isBlank()) continue
                        if (type.startsWith("audio/") || type.contains("audio")) {
                            val br = f.optInt("bitrate", f.optInt("bitrateAvg", 0))
                            if (br > audioBitrate) { audioBitrate = br; audioUrl = u }
                        } else if (type.startsWith("video/") || type.contains("video") || type.contains("mp4")) {
                            val itag = f.optString("itag", "").toIntOrNull() ?: 0
                            val h = f.optInt("height", 0).takeIf { it > 0 }
                                ?: YouTubeApiHelper.itagToHeight(itag)
                            if (h in 144..1080 && h > videoHeight) { videoHeight = h; videoUrl = u }
                        }
                    }
                }

                json.optJSONArray("formatStreams")?.let { fs ->
                    for (i in 0 until fs.length()) {
                        val f = fs.getJSONObject(i)
                        val u = f.optString("url", "")
                        if (u.isBlank()) continue
                        val itag = f.optString("itag", "").toIntOrNull() ?: 0
                        val h = f.optInt("height", 0).takeIf { it > 0 } ?: YouTubeApiHelper.itagToHeight(itag)
                        if (h >= bestMuxedH) { bestMuxedH = h; muxed = u }
                    }
                }

                if (audioUrl != null || videoUrl != null || muxed != null) {
                    try {
                        prefs.edit().putString("invidious_top", inst).apply()
                    } catch (_: Exception) {}
                    sb.append("inv OK($inst): a=${audioUrl != null} v=${videoUrl != null} m=${muxed != null}\n")
                    return StreamResult(
                        videoUrl = videoUrl, audioUrl = audioUrl, muxedUrl = muxed,
                        title = title, channelName = author, description = "",
                        debug = sb.toString(), audioUrlBest = audioUrl
                    )
                }
            } catch (_: Exception) {}
        }
        return null
    }

    // ─────────────────────────────────────────
    // NewPipe (최후 폴백, 고화질)
    // ─────────────────────────────────────────
    private suspend fun tryNewPipe(videoId: String, sb: StringBuilder): StreamResult? {
        return try {
            try { NewPipe.init(DownloaderImpl()) } catch (_: Exception) {}
            val url = "https://www.youtube.com/watch?v=$videoId"
            val info = try {
                StreamInfo.getInfo(ServiceList.YouTube, url)
            } catch (e: Exception) {
                sb.append("np err: ${e.message?.take(50)}\n")
                return null
            }
            val title = info.name ?: ""
            val channelName = try { info.uploaderName ?: "" } catch (_: Exception) { "" }
            val description = try { info.description?.content ?: "" } catch (_: Exception) { "" }

            // 오디오
            val bestAudio = try {
                info.audioStreams.filter { it.isUrl }.maxByOrNull { it.averageBitrate }?.content
            } catch (_: Exception) { null }

            // muxed (video+audio)
            val muxed = info.videoStreams.firstOrNull { !it.isVideoOnly && it.isUrl }
            if (muxed != null) {
                sb.append("np OK muxed\n")
                return StreamResult(
                    videoUrl = null, audioUrl = null, muxedUrl = muxed.content,
                    title = title, channelName = channelName, description = description,
                    debug = sb.toString(), audioUrlBest = bestAudio
                )
            }

            // video-only + audio 분리
            val videoOnly = info.videoStreams.filter { it.isUrl }.maxByOrNull {
                (it.resolution?.replace("p", "")?.toIntOrNull() ?: 0)
            }
            if (videoOnly != null && bestAudio != null) {
                sb.append("np OK video+audio\n")
                return StreamResult(
                    videoUrl = videoOnly.content, audioUrl = bestAudio, muxedUrl = null,
                    title = title, channelName = channelName, description = description,
                    debug = sb.toString(), audioUrlBest = bestAudio
                )
            }
            null
        } catch (e: Exception) { null }
    }
